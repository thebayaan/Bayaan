#!/usr/bin/env node
/**
 * Generates services/mushaf/rewayahDataManifest.ts: the sha256 of every
 * Digital Khatt SQLite asset that DigitalKhattDataService bundles (every
 * rewayah words DB, including digital-khatt-v2.db for Hafs), and of
 * services/mushaf/mushafTables.generated.ts, the generated verse index and
 * page lines. It fails when one of the DBs the tables were generated from (the
 * words DBs and digital-khatt-15-lines.db) changed since: then run
 * gen-mushaf-tables.mjs first.
 *
 * Why: the app copies each bundled DB to an on-device file named
 * `<base>.<first 8 hex chars of sha256>.db`. A changed asset therefore gets a
 * new on-device name, so installed apps import the corrected data instead of
 * reusing the copy an older release left on the device.
 *
 * The asset list is read from the require() calls in
 * services/mushaf/DigitalKhattDataService.ts, so adding a DB there and
 * re-running this script is all it takes.
 *
 *   node scripts/rewayah/gen-manifest.mjs           # rewrite the manifest
 *   node scripts/rewayah/gen-manifest.mjs --check   # exit 1 if it is stale
 *
 * services/mushaf/__tests__/rewayahDataManifest.test.ts recomputes the
 * hashes and fails CI when the committed manifest is stale.
 *
 * Release builds run the check as well (package.json), so none ships stale
 * tables: every EAS build, in the cloud or with --local, through the
 * eas-build-pre-install hook, and local iOS archives through ios:archive /
 * ios:archive:upload. Development scripts (start, ios, android, test) do not.
 * By hand:
 *
 *   npm run check:rewayah-manifest
 *
 * Plain Node (>= 18), no dependencies.
 */
import {createHash} from 'node:crypto';
import {existsSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const SERVICE_FILE = 'services/mushaf/DigitalKhattDataService.ts';
const MANIFEST_FILE = 'services/mushaf/rewayahDataManifest.ts';
const ASSET_DIR = 'data/mushaf/digitalkhatt';
const TABLES_FILE = 'services/mushaf/mushafTables.generated.ts';
const LAYOUT_SOURCE = 'digital-khatt-15-lines.db';
// A source line of TABLES_FILE: `//   <sha256> <file>`.
const TABLES_SOURCE_RE = /^\/\/ {3}([0-9a-f]{64}) (\S+)$/gm;

// require('../../data/mushaf/digitalkhatt/<file>.db'), quotes and whitespace
// tolerated. Only plain file names (no sub-directories) are bundled today.
const ASSET_REQUIRE_RE =
  /require\(\s*['"]\.\.\/\.\.\/data\/mushaf\/digitalkhatt\/([^'"/\\]+\.db)['"]\s*\)/g;

function fail(message) {
  console.error(`[gen-manifest] ${message}`);
  process.exit(1);
}

function listBundledAssets(serviceSource) {
  const files = new Set();
  for (const match of serviceSource.matchAll(ASSET_REQUIRE_RE)) {
    files.add(match[1]);
  }
  return [...files].sort();
}

function hashOfFile(absPath, algorithm) {
  return createHash(algorithm).update(readFileSync(absPath)).digest('hex');
}

// Prettier's output for this repo (80 columns): an entry too long for one
// line moves its value to its own line.
function pushEntry(lines, file, value) {
  const oneLine = `  '${file}': '${value}',`;
  if (oneLine.length <= 80) {
    lines.push(oneLine);
  } else {
    lines.push(`  '${file}':`, `    '${value}',`);
  }
}

/**
 * Fails when TABLES_FILE was generated from other files than the bundled words
 * DBs and the layout DB, or from another version of one of them.
 */
function checkTablesSources(tablesSource, entries) {
  const recorded = new Map(
    [...tablesSource.matchAll(TABLES_SOURCE_RE)].map(m => [m[2], m[1]]),
  );
  const current = new Map(entries.map(([file, sha256]) => [file, sha256]));
  const layoutPath = path.join(REPO_ROOT, ASSET_DIR, LAYOUT_SOURCE);
  if (!existsSync(layoutPath)) fail(`${ASSET_DIR}/${LAYOUT_SOURCE} not found`);
  current.set(LAYOUT_SOURCE, hashOfFile(layoutPath, 'sha256'));
  const rerun =
    'Run: node scripts/rewayah/gen-mushaf-tables.mjs (Node >= 22.13), then this script.';
  if (
    [...recorded.keys()].sort().join() !== [...current.keys()].sort().join()
  ) {
    fail(`${TABLES_FILE} was generated from other DBs. ${rerun}`);
  }
  for (const [file, sha256] of current) {
    if (recorded.get(file) !== sha256) {
      fail(`${TABLES_FILE} is stale: ${file} changed. ${rerun}`);
    }
  }
}

function renderManifest(entries, tablesSha256) {
  const lines = [
    '// AUTO-GENERATED by scripts/rewayah/gen-manifest.mjs. Do not edit by hand.',
    '//',
    '// sha256 of every Digital Khatt SQLite asset bundled by',
    '// DigitalKhattDataService, keyed by the asset file basename. The app names',
    '// each on-device copy `<base>.<first 8 hex chars>.db`, so changing an asset',
    '// changes its on-device name and installed apps re-import it.',
    '//',
    '// Regenerate after changing any bundled DB:',
    '//   node scripts/rewayah/gen-manifest.mjs',
    '// services/mushaf/__tests__/rewayahDataManifest.test.ts fails when stale.',
    '',
    'export const REWAYAH_DATA_MANIFEST: Readonly<Record<string, string>> = {',
  ];
  for (const [file, sha256] of entries) pushEntry(lines, file, sha256);
  lines.push(
    '};',
    '',
    '// md5 of the same assets: the platform file API reports md5, so the app',
    '// checks each on-device copy against it once per session and re-imports',
    '// a copy that was cut short (a copy can still open after that, with its',
    '// last words silently altered).',
    'export const REWAYAH_DATA_MD5: Readonly<Record<string, string>> = {',
  );
  for (const [file, , md5] of entries) pushEntry(lines, file, md5);
  lines.push(
    '};',
    '',
    '// sha256 of mushafTables.generated.ts: the verse index and the page lines',
    '// the app ships. It names the layout in the data identity keys, so saved',
    '// layouts stay valid until the tables change.',
    'export const MUSHAF_TABLES_SHA256 =',
    `  '${tablesSha256}';`,
    '',
  );
  return lines.join('\n');
}

function main() {
  const args = new Set(process.argv.slice(2));
  const unknown = [...args].filter(a => a !== '--check');
  if (unknown.length > 0) fail(`unknown argument(s): ${unknown.join(' ')}`);
  const checkOnly = args.has('--check');

  const servicePath = path.join(REPO_ROOT, SERVICE_FILE);
  if (!existsSync(servicePath)) fail(`${SERVICE_FILE} not found`);
  const files = listBundledAssets(readFileSync(servicePath, 'utf8'));
  if (files.length === 0) {
    fail(
      `no require('../../data/mushaf/digitalkhatt/*.db') in ${SERVICE_FILE}`,
    );
  }

  const entries = files.map(file => {
    const absPath = path.join(REPO_ROOT, ASSET_DIR, file);
    if (!existsSync(absPath)) fail(`${ASSET_DIR}/${file} does not exist`);
    if (statSync(absPath).size === 0) fail(`${ASSET_DIR}/${file} is empty`);
    return [file, hashOfFile(absPath, 'sha256'), hashOfFile(absPath, 'md5')];
  });

  const tablesPath = path.join(REPO_ROOT, TABLES_FILE);
  if (!existsSync(tablesPath)) fail(`${TABLES_FILE} not found`);
  checkTablesSources(readFileSync(tablesPath, 'utf8'), entries);
  const rendered = renderManifest(entries, hashOfFile(tablesPath, 'sha256'));
  const manifestPath = path.join(REPO_ROOT, MANIFEST_FILE);
  const existing = existsSync(manifestPath)
    ? readFileSync(manifestPath, 'utf8')
    : null;

  if (checkOnly) {
    if (existing !== rendered) {
      fail(
        `${MANIFEST_FILE} is stale. Run: node scripts/rewayah/gen-manifest.mjs`,
      );
    }
    console.log(`[gen-manifest] ${MANIFEST_FILE} is up to date`);
    return;
  }

  if (existing === rendered) {
    console.log(`[gen-manifest] ${MANIFEST_FILE} already up to date`);
  } else {
    writeFileSync(manifestPath, rendered);
    console.log(`[gen-manifest] wrote ${MANIFEST_FILE}`);
  }
  for (const [file, sha256] of entries) {
    console.log(`  ${sha256.slice(0, 8)}  ${file}`);
  }
}

main();
