"""Writes theme/surahGlyphMetrics.ts from the surah-name calligraphy font.

Each glyph in assets/fonts/surah_names.ttf has a wide blank margin on its
left (about 15% of its advance) and none on its right, and the longest names
run to 2.7 em, so laying a glyph out by its advance sets it right of centre
and lets it spill out of a tile. The table gives each surah's advance and ink
box in em so SurahGlyph can size the ink to its slot and centre it.

Run from tv-app/: python3 scripts/gen-surah-glyph-metrics.py (needs fonttools).
"""
import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
font = TTFont(ROOT / 'assets/fonts/surah_names.ttf')
upm = font['head'].unitsPerEm
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
hmtx = font['hmtx']
src = (ROOT / 'utils/surahGlyphMap.ts').read_text()
codes = {int(n): int(c, 16) for n, c in re.findall(r"(\d+): '\\u([0-9A-Fa-f]{4})'", src)}

rows = []
for surah in range(1, 115):
    name = cmap[codes[surah]]
    advance = hmtx[name][0]
    pen = BoundsPen(glyphs)
    glyphs[name].draw(pen)
    x0, y0, x1, y1 = pen.bounds
    em = lambda v: round(v / upm, 3)
    rows.append(f'  [{em(advance)}, {em(x0)}, {em(x1)}, {em(y0)}, {em(y1)}], // {surah}')

out = f"""// Generated by scripts/gen-surah-glyph-metrics.py from
// assets/fonts/surah_names.ttf. Do not edit by hand.

/**
 * Per surah (index 0 = Al-Fatihah), in em: [advance, ink left, ink right,
 * ink bottom, ink top], x from the glyph's origin, y up from the baseline.
 */
export const SURAH_GLYPH_METRICS: readonly (readonly [
  number,
  number,
  number,
  number,
  number,
])[] = [
{chr(10).join(rows)}
];

/** The font's ascender and descender, in em (hhea). */
export const SURAH_GLYPH_ASCENT = {round(font['hhea'].ascent / upm, 3)};
export const SURAH_GLYPH_DESCENT = {round(-font['hhea'].descent / upm, 3)};
"""
(Path(__file__).resolve().parents[1] / 'theme/surahGlyphMetrics.ts').write_text(out)
print('wrote', len(rows))
