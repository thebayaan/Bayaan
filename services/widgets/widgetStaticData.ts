// services/widgets/widgetStaticData.ts
// Pure builders for the static JSON bundled into both widget targets.
// Imported by scripts/generate-widget-data.ts, so no '@/' imports here.
import {surahArtworkFileName} from './artworkNames';
import {tasbeehDisplayText, tasbeehTranslation} from './dhikrText';

export interface StaticSurah {
  id: number;
  name: string;
  translatedName: string;
  glyph: string; // surah_names.ttf ("icomoon") code point
  artworkFile: string;
}

export interface StaticAyah {
  key: string;
  surahId: number;
  ayah: number;
  surahName: string;
  arabic: string; // Digital Khatt words joined by spaces, ending with the ayah marker
  translation: string; // Saheeh International, footnotes removed
}

export interface SurahSource {
  id: number;
  name: string;
  translated_name_english: string;
}

export interface AyahSources {
  words: (surahId: number, ayah: number) => string[];
  translation: (key: string) => string | undefined;
  surahName: (surahId: number) => string | undefined;
}

// Short enough for the small widget at a readable size.
export const MAX_AYAH_WORDS = 20;

export function cleanTranslation(raw: string): string {
  return raw
    .replace(/<sup[^>]*>.*?<\/sup>/g, '')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .trim();
}

export function parseVerseKey(
  key: string,
): {surahId: number; ayah: number} | null {
  const match = /^(\d{1,3}):(\d{1,3})$/.exec(key);
  if (!match) return null;
  const surahId = Number(match[1]);
  const ayah = Number(match[2]);
  if (surahId < 1 || surahId > 114 || ayah < 1) return null;
  return {surahId, ayah};
}

export function buildStaticSurahs(
  surahs: SurahSource[],
  glyphs: Record<number, string>,
): StaticSurah[] {
  return surahs.map(s => ({
    id: s.id,
    name: s.name,
    translatedName: s.translated_name_english,
    glyph: glyphs[s.id] ?? '',
    artworkFile: surahArtworkFileName(s.id),
  }));
}

export function buildStaticAyat(
  keys: string[],
  src: AyahSources,
): StaticAyah[] {
  const seen = new Set<string>();
  return keys.map(key => {
    if (seen.has(key)) throw new Error(`duplicate verse key ${key}`);
    seen.add(key);
    const parsed = parseVerseKey(key);
    if (!parsed) throw new Error(`bad verse key ${key}`);
    const words = src.words(parsed.surahId, parsed.ayah);
    if (words.length === 0) {
      throw new Error(`no Digital Khatt text for ${key}`);
    }
    // The last word is the end-of-ayah marker.
    const wordCount = words.length - 1;
    if (wordCount > MAX_AYAH_WORDS) {
      throw new Error(`${key} has ${wordCount} words, max ${MAX_AYAH_WORDS}`);
    }
    const translation = cleanTranslation(src.translation(key) ?? '');
    if (!translation) throw new Error(`no translation for ${key}`);
    const surahName = src.surahName(parsed.surahId);
    if (!surahName) throw new Error(`no surah name for ${key}`);
    return {
      key,
      surahId: parsed.surahId,
      ayah: parsed.ayah,
      surahName,
      arabic: words.join(' '),
      translation,
    };
  });
}

function swiftString(value: string): string {
  if ([...value].some(c => c.charCodeAt(0) < 0x20)) {
    throw new Error(`control character in "${value}"`);
  }
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** Swift source for targets/widgets/_shared/SurahCatalog.swift. */
export function buildSurahCatalogSwift(surahs: StaticSurah[]): string {
  const rows = surahs.map(
    s =>
      `    SurahName(id: ${s.id}, name: ${swiftString(
        s.name,
      )}, translatedName: ${swiftString(s.translatedName)}),`,
  );
  return [
    '// targets/widgets/_shared/SurahCatalog.swift',
    '// Generated by scripts/generate-widget-data.ts. Do not edit.',
    '// Compiled into the app and the widget extension, so Siri and controls',
    '// resolve surahs without the extension-only surahs.json.',
    'import Foundation',
    '',
    'struct SurahName: Hashable {',
    '  let id: Int',
    '  let name: String',
    '  let translatedName: String',
    '}',
    '',
    'enum SurahCatalog {',
    '  static let all: [SurahName] = [',
    ...rows,
    '  ]',
    '',
    '  static func surah(_ id: Int) -> SurahName? {',
    '    id >= 1 && id <= all.count ? all[id - 1] : nil',
    '  }',
    '}',
    '',
  ].join('\n');
}

// ---- Phase 3: adhkar periods --------------------------------------------

export type AdhkarPeriodName = 'morning' | 'evening';

export interface FeaturedDhikr {
  id: string;
  arabic: string;
  translation: string | null;
  repeatCount: number;
}

export interface SessionDhikr {
  id: string;
  translation: string | null;
  repeatCount: number; // >= 1
  audioFile: string | null;
  mediumText: string;
  mediumCut: boolean;
  largeText: string;
  largeCut: boolean;
}

export interface AdhkarPeriodData {
  period: AdhkarPeriodName;
  superId: string;
  title: string;
  arabicTitle: string;
  count: number; // adhkar in the period's dhikr list
  featured: FeaturedDhikr[];
  items: SessionDhikr[]; // the whole category, in order_index order
}

export interface AdhkarPeriods {
  morning: AdhkarPeriodData;
  evening: AdhkarPeriodData;
}

export interface AdhkarPeriodSource {
  superId: string;
  title: string;
  arabicTitle: string;
  featured: string[];
}

export interface AdhkarSeedRow {
  id: string;
  category_id: string;
  arabic: string;
  translation: string | null;
  repeat_count: number;
  audio_file: string | null;
  order_index: number;
}

export const MAX_FEATURED_DHIKR_CHARS = 180;
export const SESSION_MEDIUM_CHARS = 120;
export const SESSION_LARGE_CHARS = 420;
function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isStringList(value: unknown): value is string[] {
  return Array.isArray(value) && value.every(v => typeof v === 'string');
}

function isPeriodSource(value: unknown): value is AdhkarPeriodSource {
  return (
    isObject(value) &&
    typeof value.superId === 'string' &&
    typeof value.title === 'string' &&
    typeof value.arabicTitle === 'string' &&
    isStringList(value.featured)
  );
}

export function isAdhkarPeriodSources(
  value: unknown,
): value is Record<AdhkarPeriodName, AdhkarPeriodSource> {
  return (
    isObject(value) &&
    isPeriodSource(value.morning) &&
    isPeriodSource(value.evening)
  );
}

function isSeedRow(value: unknown): value is AdhkarSeedRow {
  return (
    isObject(value) &&
    typeof value.id === 'string' &&
    typeof value.category_id === 'string' &&
    typeof value.arabic === 'string' &&
    (value.translation === null || typeof value.translation === 'string') &&
    typeof value.repeat_count === 'number' &&
    (value.audio_file === undefined ||
      value.audio_file === null ||
      typeof value.audio_file === 'string') &&
    (value.order_index === undefined || typeof value.order_index === 'number')
  );
}

export function parseAdhkarSeed(seed: unknown): AdhkarSeedRow[] {
  if (!isObject(seed) || !Array.isArray(seed.adhkar)) return [];
  const rows: unknown[] = seed.adhkar;
  return rows.filter(isSeedRow).map(row => ({
    ...row,
    audio_file: row.audio_file ?? null,
    order_index: row.order_index ?? 0,
  }));
}

// Session card text: the (( )) dhikr when marked, else the whole text
// without bare parentheses (Ayat al-Kursi, the three Quls).
export function sessionDhikrText(arabic: string): string {
  const marked = tasbeehDisplayText(arabic);
  const text =
    marked ?? arabic.replace(/[()]/g, ' ').replace(/\s+/g, ' ').trim();
  return text.replace(/[\s.،,:]+$/, '');
}

// Ordered dhikr ids per super category (data/adhkar.json
// super_category_dhikr_ids); the same lists the app's screens use.
export type AdhkarSeedLists = Record<string, string[]>;

export function parseAdhkarSeedLists(seed: unknown): AdhkarSeedLists {
  const raw = isObject(seed) ? seed.super_category_dhikr_ids : undefined;
  if (!isObject(raw)) return {};
  const lists: AdhkarSeedLists = {};
  for (const [superId, ids] of Object.entries(raw)) {
    if (isStringList(ids)) lists[superId] = ids;
  }
  return lists;
}

// Text that fits within budget characters, cut at a word boundary with an
// ellipsis when it does not.
export function cutToBudget(
  text: string,
  budget: number,
): {text: string; cut: boolean} {
  if (text.length <= budget) return {text, cut: false};
  const head = text.slice(0, budget - 1);
  const space = head.lastIndexOf(' ');
  return {
    text: `${(space > 0 ? head.slice(0, space) : head).trim()}…`,
    cut: true,
  };
}

function sessionItem(row: AdhkarSeedRow): SessionDhikr {
  const text = sessionDhikrText(row.arabic);
  const medium = cutToBudget(text, SESSION_MEDIUM_CHARS);
  const large = cutToBudget(text, SESSION_LARGE_CHARS);
  return {
    id: row.id,
    translation: tasbeehTranslation(row.translation),
    repeatCount: Math.max(1, row.repeat_count),
    audioFile: row.audio_file,
    mediumText: medium.text,
    mediumCut: medium.cut,
    largeText: large.text,
    largeCut: large.cut,
  };
}

export function buildAdhkarPeriods(
  source: Record<AdhkarPeriodName, AdhkarPeriodSource>,
  seed: AdhkarSeedRow[],
  lists: AdhkarSeedLists,
): AdhkarPeriods {
  function period(name: AdhkarPeriodName): AdhkarPeriodData {
    const src = source[name];
    const ids = lists[src.superId];
    if (!ids || ids.length === 0) {
      throw new Error(`${name}: no dhikr list for ${src.superId}`);
    }
    if (src.featured.length === 0) {
      throw new Error(`${name} has no featured adhkar`);
    }
    const featured = src.featured.map(id => {
      if (!ids.includes(id)) {
        throw new Error(
          `${name}: dhikr ${id} is not in the ${src.superId} list`,
        );
      }
      const row = seed.find(d => d.id === id);
      if (!row)
        throw new Error(`${name}: dhikr ${id} is missing from the seed`);
      const arabic = tasbeehDisplayText(row.arabic);
      if (!arabic) throw new Error(`${name}: dhikr ${id} has no (( )) text`);
      if (arabic.length > MAX_FEATURED_DHIKR_CHARS) {
        throw new Error(`${name}: dhikr ${id} is too long`);
      }
      return {
        id,
        arabic,
        translation: tasbeehTranslation(row.translation),
        repeatCount: row.repeat_count,
      };
    });
    return {
      period: name,
      superId: src.superId,
      title: src.title,
      arabicTitle: src.arabicTitle,
      count: ids.length,
      featured,
      items: ids.map(id => {
        const row = seed.find(d => d.id === id);
        if (!row)
          throw new Error(`${name}: dhikr ${id} is missing from the seed`);
        return sessionItem(row);
      }),
    };
  }
  return {morning: period('morning'), evening: period('evening')};
}
