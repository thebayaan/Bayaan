/** The search spellings of each word of the verses, in order. */
function verseWords(verses: string): string[][] {
  const [surah, ayahs] = verses.split(':');
  const [from, to = from] = ayahs.split('-');
  const words: string[][] = [];
  for (let ayah = Number(from); ayah <= Number(to); ayah++) {
    const rows = readVerse.all(Number(surah), ayah) as {text: string}[];
    if (rows.length === 0) throw new Error(`no words for ${surah}:${ayah}`);
    for (const {text} of rows) {
      if (isVerseMarker(text)) continue;
      const s = quranWordSpellings(text);
      words.push([s.imlaei, ...s.alternates, s.rasm, ...s.mixed]);
    }
  }
  return words;
}

/** The quoted words folded like typed search words, punctuation dropped. */
function quotedWords(quote: string): string[] {
  return quote
    .replace(/[،؛؟:.!()«»"]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map(foldQuranQueryWord);
}

/** True when the quoted words are a run of the verse words. */
function isRunOf(quoted: string[], verse: string[][]): boolean {
  for (let start = 0; start + quoted.length <= verse.length; start++) {
    const fits = quoted.every((word, i) => {
      const spellings = verse[start + i];
      if (spellings.includes(word)) return true;
      // A leading و or ف of the verse's first quoted word may be dropped.
      return (
        i === 0 &&
        spellings.some(
          s => (s[0] === 'و' || s[0] === 'ف') && s.slice(1) === word,
        )
      );
    });
    if (fits) return true;
  }
  return false;
}

describe('Arabic theme titles that quote a verse', () => {
  it.each(QUOTES)('%s quotes %s word for word', (theme, verses, quote) => {
    expect(arabic.themes[theme]).toContain(quote);
    expect(isRunOf(quotedWords(quote), verseWords(verses))).toBe(true);
  });

  it('rejects a quote with one word changed', () => {
    // The wording 43:68 had before: لو كان لله ولد لكنت أول العابدين.
    expect(
      isRunOf(
        quotedWords('لو كان لله ولد لكنت أول العابدين'),
        verseWords('43:81'),
      ),
    ).toBe(false);
    expect(isRunOf(quotedWords('وهو كل يوم في شأن'), verseWords('55:29'))).toBe(
      false,
    );
  });
});
